"""Reproduce the seed-sweep numbers in the README and write docs/sweep_results.md.

Usage: python scripts/run_sweeps.py [--workers 2] [--scale 1.0]
"""

from __future__ import annotations

import argparse
import time
from pathlib import Path

from consensus_robustness.sweep import sweep

HONEST = [("raft", 3, 5000), ("raft", 5, 5000), ("bft", 4, 5000), ("bft", 7, 2000)]
MUTANT = [
    ("bft", 4, "quorum_2f", 2000),
    ("bft", 3, "n_eq_3f", 2000),
    ("bft", 4, "no_lock", 2000),
    ("raft", 3, "no_log_check", 2000),
    ("raft", 3, "stale_votes", 2000),
    ("raft", 4, "small_quorum", 2000),
    ("raft", 3, "commit_old_term", 2000),
]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--workers", type=int, default=2)
    ap.add_argument("--scale", type=float, default=1.0)
    ap.add_argument("--out", default="docs/sweep_results.md")
    a = ap.parse_args()
    out = [
        "# Seed-sweep results",
        "",
        "Generated by `python scripts/run_sweeps.py`. Each seed draws a random",
        "fault schedule with `consensus_robustness.faults.random_scenario` (seeds 0..N-1).",
        "",
    ]
    out += ["## Honest protocols", "", "```text"]
    t0 = time.perf_counter()
    for protocol, n, seeds in HONEST:
        rep = sweep(protocol, n, range(int(seeds * a.scale)), workers=a.workers)
        print(rep.summary(), flush=True)
        out.append(rep.summary())
    out += ["```", "", "## Mutants (random sweep, no shrinking)", "", "```text"]
    for protocol, n, mutant, seeds in MUTANT:
        rep = sweep(protocol, n, range(int(seeds * a.scale)), mutant=mutant, workers=a.workers)
        print(rep.summary(), flush=True)
        out.append(rep.summary())
    out += ["```", "", f"Total wall time: {time.perf_counter() - t0:.0f} s on {a.workers} worker processes.", ""]
    Path(a.out).write_text("\n".join(out))
    print(f"wrote {a.out}")


if __name__ == "__main__":
    main()
